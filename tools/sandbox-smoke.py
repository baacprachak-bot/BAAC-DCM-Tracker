"""Run against a fresh local trial database; never against the live service."""
from pathlib import Path
import json
from playwright.sync_api import sync_playwright, expect
root=Path(__file__).resolve().parent.parent
out=root/'docs/screenshots';out.mkdir(exist_ok=True)
base='http://127.0.0.1:3210'
results=[]
with sync_playwright() as p:
 browser=p.chromium.launch(executable_path='/usr/bin/chromium',headless=True,args=['--no-sandbox'])
 page=browser.new_page(viewport={'width':390,'height':844},device_scale_factor=1)
 errors=[];page.on('pageerror',lambda e:errors.append(str(e)))
 page.goto(base+'/sandbox')
 expect(page.get_by_role('heading',name='บันทึกข้อมูลลูกค้า',exact=True)).to_be_visible()
 expect(page.locator('#demo')).to_contain_text('ฐานข้อมูลสมมติแยก')
 results.append('พื้นที่ทดลองแสดงคำกำกับและเลือกบทบาทได้')
 cif='00889900'
 for _ in range(2):
  page.locator('[name=firstName]').fill('ทดลองผ่านหน้าจอ')
  page.locator('[name=lastName]').fill('ข้อมูลสมมติ')
  page.locator('[name=cif]').fill(cif)
  page.get_by_role('button',name='บันทึกและส่งรออนุมัติ').click()
  expect(page.locator('#message')).to_contain_text('บันทึกสำเร็จ' if _==0 else 'มีรายการรออนุมัติแล้ว')
 results.extend(['บันทึกลูกค้าสมมติได้','ป้องกัน CIF ซ้ำขณะรออนุมัติ'])
 page.select_option('#role','assistant_manager')
 expect(page.get_by_role('heading',name='รายการรออนุมัติ',exact=True)).to_be_visible()
 expect(page.locator('article').filter(has_text=cif)).to_be_visible()
 page.screenshot(path=str(out/'trial-pending.png'),full_page=True)
 page.locator('article').filter(has_text=cif).get_by_role('button',name='อนุมัติรายการ',exact=True).click()
 page.get_by_role('button',name='ย้อนกลับ',exact=True).click()
 expect(page.locator('article').filter(has_text=cif)).to_be_visible()
 results.append('ยกเลิกการยืนยันแล้วรายการยังรออนุมัติ')
 page.locator('article').filter(has_text=cif).get_by_role('button',name='อนุมัติรายการ',exact=True).click()
 page.get_by_role('button',name='ยืนยันอนุมัติ',exact=True).click()
 expect(page.locator('#message')).to_contain_text('อนุมัติสำเร็จ')
 page.locator('nav button[data-page=approved]').click()
 expect(page.locator('article').filter(has_text=cif)).to_contain_text('อนุมัติโดย')
 results.append('ผู้ช่วยผู้จัดการอนุมัติแล้วรายการย้ายไปประวัติพร้อมชื่อและเวลา')
 page.screenshot(path=str(out/'trial-approved.png'),full_page=True)
 page.select_option('#role','manager')
 expect(page.get_by_role('heading',name='รายการรออนุมัติ',exact=True)).to_be_visible()
 page.locator('article').filter(has_text='00001001').get_by_role('button',name='อนุมัติรายการ',exact=True).click()
 page.get_by_role('button',name='ยืนยันอนุมัติ',exact=True).click()
 expect(page.locator('#message')).to_contain_text('อนุมัติสำเร็จ')
 results.append('ผู้จัดการสาขาอนุมัติได้เช่นกัน')
 page.get_by_role('textbox',name='ค้นหารายการ').fill('00001002')
 page.get_by_role('button',name='ค้นหา',exact=True).click()
 expect(page.locator('article')).to_have_count(1)
 expect(page.locator('article')).to_contain_text('00001002')
 results.append('ค้นหาด้วย CIF และรักษาศูนย์นำหน้า')
 page.reload()
 expect(page.get_by_role('heading',name='บันทึกข้อมูลลูกค้า',exact=True)).to_be_visible()
 page.select_option('#role','manager')
 expect(page.get_by_role('heading',name='รายการรออนุมัติ',exact=True)).to_be_visible()
 page.locator('nav button[data-page=approved]').click()
 expect(page.locator('article').filter(has_text=cif)).to_be_visible()
 results.append('โหลดหน้าใหม่แล้วข้อมูลอนุมัติยังอยู่')
 page.select_option('#role','pending')
 expect(page.get_by_role('heading',name='เข้าสู่ระบบ LINE สำเร็จแล้ว',exact=True)).to_be_visible()
 expect(page.locator('nav button:disabled')).to_have_count(3)
 results.append('เจ้าหน้าที่ไม่มีสิทธิ์ไม่เห็นข้อมูลและทำรายการไม่ได้')
 page.select_option('#role','admin')
 expect(page.get_by_role('heading',name='กำหนดสิทธิ์เจ้าหน้าที่',exact=True)).to_be_visible()
 member=page.locator('article').filter(has_text='demo-pending')
 member.locator('select').nth(0).select_option('manager')
 member.locator('select').nth(1).select_option('active')
 member.get_by_role('button',name='บันทึกสิทธิ์',exact=True).click()
 expect(page.locator('#message')).to_contain_text('บันทึกสิทธิ์เจ้าหน้าที่แล้ว')
 page.select_option('#role','pending')
 expect(page.get_by_role('heading',name='รายการรออนุมัติ',exact=True)).to_be_visible()
 results.append('ผู้ดูแลเปิดสิทธิ์ให้บัญชีสมมติแล้วใช้งานได้')
 page.select_option('#role','admin')
 expect(page.get_by_role('heading',name='กำหนดสิทธิ์เจ้าหน้าที่',exact=True)).to_be_visible()
 member=page.locator('article').filter(has_text='demo-pending')
 member.locator('select').nth(1).select_option('suspended')
 member.get_by_role('button',name='บันทึกสิทธิ์',exact=True).click()
 expect(page.locator('#message')).to_contain_text('บันทึกสิทธิ์เจ้าหน้าที่แล้ว')
 page.select_option('#role','pending')
 expect(page.get_by_role('heading',name='บัญชีนี้ถูกระงับการใช้งาน',exact=True)).to_be_visible()
 results.append('ระงับบัญชีสมมติแล้วเข้าใช้งานไม่ได้ทันที')
 assert not errors,errors
 results.append('ไม่พบ JavaScript error ระหว่างทดสอบ')
 browser.close()
(root/'docs/simulation-results.json').write_text(json.dumps({'mode':'local-admin-sandbox','passed':results,'browserErrors':errors},ensure_ascii=False,indent=2)+'\n')
print('Browser trial passed:',len(results),'scenarios')
for item in results:print('PASS:',item)
